"""
cardiac_em — электромеханика сердечной ткани на DOLFINx
========================================================

Пакет разделён на слои со строго однонаправленными зависимостями:

    config/    → чистые данные (dataclasses), БЕЗ DOLFINx
    fem/       → сетки, функциональные пространства, поля параметров
    models/    → модели клетки, активного напряжения, пассивной механики
    solvers/   → монодоменная электрика, квазистатическая механика
    coupling/  → перенос полей между электрической и механической сетками
    runtime/   → расписание событий, наблюдатели, основной цикл
    io/        → чекпоинты, поля (XDMF/VTK), манифест прогона
    control/   → как прогоны запускаются (CLI, серии, будущий API)
    analysis/  → постобработка; читает ТОЛЬКО файлы, без DOLFINx

Правило направления: модуль может импортировать только из слоёв выше
себя в этом списке. `analysis/` не импортирует ничего из расчётной
части вообще — он работает с файлами результатов и потому запускается
в лёгком окружении (numpy/pandas), без FEM-стека.

ВАЖНО: этот `__init__.py` намеренно НЕ импортирует подпакеты.
`import cardiac_em.config` обязан работать в окружении без DOLFINx —
на этом держится возможность готовить и валидировать конфигурации
серий экспериментов отдельно от расчётной машины.

Подробности — в ARCHITECTURE.md.
"""

