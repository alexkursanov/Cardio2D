"""
Законы активного напряжения на уровне ткани.
=============================================

Клетка передаёт ткани «изометрическую» силу T_iso — то, что она
развивала бы, если бы волокно не двигалось. Закон здесь превращает её в
действующее напряжение с учётом скорости волокна:

    T_act = T_iso · φ(v),   v — скорость, выраженная через растяжение
                             волокна λ_f(u) и его значение на прошлом
                             механическом шаге

Зачем φ(v) живёт в ткани, а не в клетке. Сила сократительного элемента
сильно зависит от скорости (у TNNPM наклон p'(0) ≈ 800 на мкм/мс), и
если брать скорость с прошлого шага, связь электрика–механика
неустойчива: это вязкий демпфер, посчитанный явно. Проверено цепочкой
из двух элементов: явная схема разносится за несколько шагов при любом
dt_мех, а неявная по скорости (φ(v(u)) в форме равновесия) устойчива и
при dt_мех = 1 мс отличается от dt_мех = 0.1 мс на 0.5 % по пику силы.
Доля прикреплённых мостиков N при этом берётся с начала шага — она
меняется медленно (характерное время ~60 мс).

Слой требует UFL (как `models/passive`).
"""

