"""
Абстракция пассивного материала.
=================================

Материал отвечает на один вопрос: каков второй тензор Пиолы–Кирхгофа
S при данном градиенте деформации F и данных параметрах ткани.
Всё остальное — сборка форм, граничные условия, решатель — дело
солвера и от выбора материала не зависит.

В отличие от `models/cell/`, этот слой РАБОТАЕТ С UFL и потому требует
DOLFINx: выражение для S подставляется прямо в вариационную форму, и
якобиан из него получается автоматическим дифференцированием.

Кинематика
----------
    F = I + ∇u        градиент деформации
    C = Fᵀ·F          правый тензор Коши–Грина
    J = det F         изменение объёма
    I₁ = tr C         первый инвариант
    I₄ = f₀·C·f₀      растяжение вдоль волокна в квадрате

Все инварианты считает `kinematics()`, чтобы реализации материалов не
повторяли одно и то же и не разошлись в определениях.
"""

from __future__ import annotations

from abc import ABC, abstractmethod

from ufl import Identity, det, dot, grad, tr

__all__ = ["PassiveMaterial", "kinematics"]


def kinematics(u, tissue):
    """
    Вернуть (F, C, J, I₁, I₄) для поля перемещений u.

    Направление волокна берётся из `tissue` и может меняться по ткани —
    например, если регион переопределяет FIBER_ANGLE_DEG.
    """
    I = Identity(u.ufl_shape[0])
    F = I + grad(u)
    C = F.T * F
    J = det(F)
    I1 = tr(C)
    f0 = tissue.fiber_vector()
    I4 = dot(f0, C * f0)
    return F, C, J, I1, I4


class PassiveMaterial(ABC):
    """
    Базовый класс модели пассивной упругости.

    Атрибуты класса
    ---------------
    name        : короткое имя для реестра и сообщений
    param_names : какие параметры ткани нужны материалу; солвер
                  проверяет, что они построены на механической сетке
    """

    name: str = "abstract"
    param_names: tuple[str, ...] = ()

    @abstractmethod
    def second_piola(self, u, tissue):
        """
        Второй тензор Пиолы–Кирхгофа S как UFL-выражение.

        Возвращается именно S, а не P = F·S: так материал не обязан
        знать, в какой форме солвер собирает слабую формулировку, а
        активное напряжение складывается с пассивным на уровне S, где
        обе части имеют одинаковый смысл.
        """

    def describe(self) -> str:
        return f"{self.name} (параметры: {', '.join(self.param_names)})"
