"""
Модель Роджерса–МакКаллоха (1994) — модифицированный ФитцХью–Нагумо.
====================================================================

    du/dt = c1·u·(u − a)·(1 − u) − c2·u·v + I_stim
    dv/dt = b·(u − d·v)

где u — безразмерный трансмембранный потенциал (0 — покой, 1 — плато),
v — переменная восстановления. Время в мс.

О НАЗВАНИИ. В прежнем монолитном скрипте класс назывался
`AlievPanfilov`, хотя выписанные в нём уравнения — именно
Роджерса–МакКаллоха. У Алиева–Панфилова (1996) правые части другие:

    du/dt = k·u·(u − a)·(1 − u) − u·v
    dv/dt = ε(u, v)·(−v − k·u·(u − a − 1))

— член связи `−u·v` вместо `−c2·u·v` и совсем иное уравнение
восстановления с зависящим от состояния ε. Здесь класс назван по
фактическим уравнениям; если понадобится настоящий Алиев–Панфилов, это
будет отдельная модель в этом же каталоге.

Воротных переменных в модели нет: обе переменные интегрируются явным
Эйлером. Механизм Раша–Ларсена базового класса при этом не
задействуется — он понадобится подробным ионным моделям.

Активное напряжение задаётся феноменологически: T_act = T_max·u·(1−u).
Множитель u·(1−u) безразмерен и достигает максимума 1/4 при u = 1/2,
поэтому пиковое напряжение составляет T_max/4. Это в точности поведение
прежнего скрипта — оно сохранено, чтобы результаты пакета можно было
сверить с эталоном в `legacy/`.
"""

from __future__ import annotations

import numpy as np

from .base import CellModel

__all__ = ["RogersMcCullochModel"]


class RogersMcCullochModel(CellModel):
    """Двухпеременная феноменологическая модель возбуждения."""

    name = "rogers_mcculloch"
    state_names = ("u", "v")
    v_index = 0
    gate_indices = ()                      # воротных переменных нет
    param_names = ("AP_c1", "AP_c2", "AP_a", "AP_b", "AP_d")
    tension_kind = "scaled"
    suggested_dt_ms = 0.05

    # Ограничение сверху на u — страховка от разгона явной схемы при
    # слишком крупном шаге. Перенесено из прежнего скрипта как есть:
    # в норме u не подходит к этой границе, а при подходе означает, что
    # шаг великоват.
    state_bounds = {0: (0.0, 1.1)}

    def resting_state(self) -> np.ndarray:
        return np.array([0.0, 0.0])

    def rhs_non_gate(self, t: float, y: np.ndarray, stim: np.ndarray,
                     params: dict[str, np.ndarray]) -> np.ndarray:
        u = y[:, 0]
        v = y[:, 1]

        c1 = params["AP_c1"]
        c2 = params["AP_c2"]
        a = params["AP_a"]
        b = params["AP_b"]
        d = params["AP_d"]

        du = c1 * u * (u - a) * (1.0 - u) - c2 * u * v + stim
        dv = b * (u - d * v)

        return np.stack((du, dv), axis=1)

    def active_tension(self, y: np.ndarray,
                       params: dict[str, np.ndarray]) -> np.ndarray:
        """
        Безразмерный сигнал u·(1−u) ∈ [0, 1/4]. Вызывающий умножает его
        на T_MAX и обрезает снизу нулём (u может слегка выйти за [0, 1]
        при крупном шаге, и тогда произведение стало бы отрицательным).
        """
        u = y[:, 0]
        return u * (1.0 - u)
